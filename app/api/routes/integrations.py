def _peek_request_id(body: bytes) -> object:
    """The caller's correlation id, before the body has been trusted for anything else."""
    try:
        parsed = json.loads(body.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError):
        return ""
    return parsed.get("request_id", "") if isinstance(parsed, dict) else ""


def _parse(body: bytes) -> ErpQueryRequest:
    try:
        return ErpQueryRequest.model_validate_json(body)
    except PydanticValidationError as exc:
        first = exc.errors()[0] if exc.errors() else {}
        where = ".".join(str(p) for p in first.get("loc", ())) or "body"
        raise ValidationError(
            f"طلب غير صالح عند '{where}': {first.get('msg', 'قيمة غير مقبولة')}.",
            error_code="INVALID_REQUEST",
        ) from exc


def _check_tenant(client: AuthenticatedClient, payload: ErpQueryRequest) -> None:
    """Refused before retrieval, so no other tenant's data is fetched to be filtered.

    This is the whole of tenant isolation in Phase 1, and it is honest about its reach:
    there is no `tenant_id` on a document, a chunk or a section, so one instance cannot
    separate two tenants' corpora however the request is worded. What it can do is
    guarantee that a credential issued for one tenant is never served under the name of
    another — which, with one instance per tenant, is the same guarantee.
    """
    if payload.tenant_id != client.tenant_id:
        logger.warning(
            "Tenant mismatch refused: key=%s declared=%s request_id=%s",
            client.key_id, _echo_id(payload.tenant_id), payload.request_id,
        )
        raise TenantMismatchError("المستأجر المطلوب لا يطابق مفتاح التكامل.")


def _check_scopes(client: AuthenticatedClient, payload: ErpQueryRequest) -> None:
    """A request narrows what the credential may read. It can never widen it."""
    requested = {s.strip().lower() for s in payload.retrieval.knowledge_scopes if s.strip()}
    if not requested:
        return
    permitted = {s.lower() for s in client.allowed_scopes} & PHASE_1_SCOPES
    beyond = sorted(requested - permitted)
    if beyond:
        raise ScopeDeniedError(
            f"نطاقات المعرفة التالية غير مسموحة لهذا المفتاح: {', '.join(beyond)}."
        )


def _web_decision(
    client: AuthenticatedClient, payload: ErpQueryRequest, operator_enabled: bool
) -> bool:
    """Whether this one call may reach the internet.

    The refusal is structural and comes before anything else happens: a call carrying
    ERP data and asking for web search is rejected outright rather than served with the
    search quietly switched off. Serving it would leave the caller's bug in place until
    the day this check is the only thing between a supplier's prices and a public search
    engine — and the question sent to a provider is the caller's own wording, verbatim.

    Three locks, all of which must be open: the request asked, the operator allowed it
    for this credential, and the instance has web search on at all.
    """
    if payload.context.erp_facts:
        if payload.web_search_allowed:
            logger.warning(
                "Refused: web search requested on a call carrying %s ERP fact(s), key=%s",
                len(payload.context.erp_facts), client.key_id,
            )
            raise WebSearchNotPermittedError(
                "لا يجوز تفعيل البحث على الويب في طلب يحمل بيانات ERP."
            )
        return False
    return bool(payload.web_search_allowed and client.web_search_allowed and operator_enabled)


def _reject_unsupported_context(payload: ErpQueryRequest) -> None:
    """ERP facts are refused in Phase 1 rather than accepted and ignored.

    Accepting them would be the dangerous option. The caller would send live purchasing
    figures, ask whether they comply with the filed policy, and receive a confident
    answer about the policy alone — with no sign anywhere in the reply that the figures
    it named were never read. Answering from supplied live data is Phase 6 work:
    sanitising it as untrusted input, framing it in the prompt as data rather than
    instructions, reporting it in its own list, and measuring what it does to the
    context window. None of that is approved yet, so the honest reply is a refusal that
    says which phase it belongs to.

    The validation above still runs, and the web rule above still fires first, so the
    security check that matters is exercised on exactly the request that threatens it.
    """
    if payload.context.erp_facts:
        raise UnsupportedContextError(
            "تمرير context.erp_facts غير مدعوم في المرحلة الأولى؛ "
            "الإجابة من البيانات الحية ضمن نطاق مرحلة لاحقة.",
            error_code="ERP_FACTS_NOT_SUPPORTED_IN_PHASE_1",
        )


