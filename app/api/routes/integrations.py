def _to_response(payload: ErpQueryRequest, chat: ChatResponse) -> ErpQueryResponse:
    """Internal shape to wire shape. The four citation lists stay four lists."""
    answered = chat.answer_source != "none"
    timings = chat.timings_ms or {}

    warnings: list[str] = []
    conflicts: list[str] = []
    if chat.validation is not None:
        warnings = list(chat.validation.warnings)
        conflicts = list(chat.validation.conflicts)

    live = False if answered else needs_live_data(payload.query)

    return ErpQueryResponse(
        request_id=payload.request_id,
        answer_id=chat.answer_id,
        answered=answered,
        answer=chat.answer,
        answer_source=chat.answer_source,
        grounded=chat.grounded,
        language=payload.language or (chat.plan.language if chat.plan else "") or "ar",
        model=chat.model,
        latency_ms=LatencyBreakdown(
            total=timings.get("total_ms", 0),
            retrieval=timings.get("retrieval_ms"),
            generation=timings.get("generation_ms") or timings.get("web_generation_ms"),
        ),
        sources=[
            DocumentSource(
                citation=s.citation,
                document_id=s.document_id,
                filename=s.filename,
                title=s.title,
                section=s.section,
                section_path=s.section_path,
                locator=s.locator,
                page=s.page,
                version=s.version,
                category=s.category,
                tier=str(s.tier),
                score=round(s.score, 4),
                excerpt=s.excerpt,
            )
            for s in chat.sources
        ],
        knowledge_sources=[
            KnowledgeSource(
                item_id=k.item_id,
                version_id=k.version_id,
                version_no=k.version_no,
                type=k.type,
                scope=k.scope,
                content=k.content,
                source_text=k.source_text,
                confidence=k.confidence,
                influence=k.influence,
                conflicted=k.conflicted,
            )
            for k in chat.knowledge
        ],
        web_sources=[
            WebSourceRef(
                citation=w.citation,
                title=w.title,
                url=w.url,
                domain=w.domain,
                snippet=w.snippet,
                authoritative=w.authoritative,
            )
            for w in chat.web_sources
        ],
        # Nothing is supplied in Phase 1, and the list is still present rather than
        # absent: a caller that reads four lists on every reply never has to ask
        # whether a missing one means "none" or "this build does not report them".
        erp_facts_used=[],
        computed_values=[
            ComputedValue(
                kind=d.kind,
                label=d.label,
                computed=d.computed,
                stated=d.stated,
                holds=d.holds,
                difference=d.difference,
                operands=list(d.operands),
                citation=d.citation,
                locator=d.locator,
            )
            for d in chat.derived
        ],
        warnings=warnings,
        conflicts=conflicts,
        needs_live_data=live,
        suggested_source=suggested_source(payload.query) if live else None,
    )


