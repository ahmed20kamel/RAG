"""The ERP integration surface.

One endpoint, deliberately not `/api/chat`. The chat route exists to serve a browser: it
returns the pipeline diagnostics the interface draws, it changes shape whenever the
interface needs something new, and it writes a learning-candidate row whenever a message
reads like someone teaching the system something. All three are right for a person and
wrong for a program. A machine caller needs a contract that is versioned, minimal and
side-effect free, and it should not quietly fill a human reviewer's queue with rows
generated by a loop.

What it does *not* do is re-implement anything. Retrieval, ranking, grounding, refusal,
conflict handling and the citation split all come from `RagService.answer()`, exactly as
the web interface gets them. This module is a door with locks on it, not a second
system: authentication, tenant binding, the limits that keep one caller from taking the
whole model, the structural refusal of web search when ERP data is present, and the
translation between the wire contract and the internal one.

Phase 1 scope. `context.erp_facts` is validated and then refused rather than accepted
and ignored — see `_reject_unsupported_context`.
"""

