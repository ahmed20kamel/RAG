logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api/v1/integrations/erp", tags=["integrations"])

ENDPOINT_PATH = "/api/v1/integrations/erp/query"
#: Phase 1 issues credentials that read approved organisational knowledge and nothing
#: narrower. Personal and team items belong to people who have accounts here; an ERP
#: user has none, so there is no identity to match them against.
PHASE_1_SCOPES = frozenset({"global"})
_SAFE_ID = re.compile(r"[^A-Za-z0-9_-]")


def _echo_id(raw: object) -> str:
    """A correlation id safe to put in a reply to an unauthenticated caller.

    Echoed so a failed call is still traceable from the other system's logs, and
    stripped first so nothing arriving from outside is reflected back verbatim.
    """
    if not isinstance(raw, str):
        return ""
    return _SAFE_ID.sub("", raw)[:64]


@router.post("/query", response_model=ErpQueryResponse)
async def erp_query(request: Request, container: ContainerDep, response: Response):
    settings = container.settings
    if not settings.integration_enabled:
        raise IntegrationDisabledError("واجهة التكامل غير مفعّلة على هذا الخادم.")

    started = time.perf_counter()

    # The raw bytes, because they are what was signed. Re-serialising a parsed object
    # and signing that would break on any difference in key order or spacing, and would
    # quietly stop verifying that the bytes on the wire were the bytes the caller sent.
    body = await request.body()
    if len(body) > settings.integration_max_body_bytes:
        raise PayloadTooLargeError(
            f"حجم الطلب يتجاوز الحد المسموح ({settings.integration_max_body_bytes} بايت)."
        )

    request.state.request_id = _echo_id(_peek_request_id(body))

    container.integration_auth.check_transport(
        request.url.scheme, request.headers.get("x-forwarded-proto", "")
    )

    presented = PresentedCredential(
        authorization=request.headers.get("authorization", ""),
        key_id_header=request.headers.get("x-rag-key-id", ""),
        timestamp=request.headers.get("x-rag-timestamp", ""),
        nonce=request.headers.get("x-rag-nonce", ""),
        signature=request.headers.get("x-rag-signature", ""),
        body=body,
    )
    idempotency_key = (request.headers.get("idempotency-key", "") or "").strip()[:128]

    client: AuthenticatedClient | None = None
    payload: ErpQueryRequest | None = None
    try:
        with session_scope() as db:
            client = container.integration_auth.authenticate(
                db, presented, method="POST", path=ENDPOINT_PATH
            )

            # Immediately after the credential is known and before anything else is
            # done with the body. Placed after validation, a caller looping on a
            # malformed request would never be slowed down: every attempt would be
            # refused by the parser before reaching the limiter, while the database took
            # the full rate of authentications. A caller stuck in a loop should be told
            # to back off, whatever is wrong with what it is sending.
            container.integration_rate_limiter.check(
                client.key_id,
                per_minute=client.rate_limit_per_minute,
                burst=client.rate_limit_burst,
            )
            check_quota(db, client.client_id, client.daily_quota)

            payload = _parse(body)
            request.state.request_id = payload.request_id

            _check_tenant(client, payload)
            _check_scopes(client, payload)
            web_allowed = _web_decision(client, payload, settings.web_search_enabled)
            _reject_unsupported_context(payload)

            if idempotency_key:
                replay = container.integration_idempotency.begin(
                    db,
                    client_id=client.client_id,
                    key=idempotency_key,
                    body_hash=body_fingerprint(body),
                )
                if replay is not None:
                    logger.info(
                        "Idempotent replay for request_id=%s key=%s",
                        payload.request_id, client.key_id,
                    )
                    response.headers["Idempotent-Replay"] = "true"
                    _audit(
                        payload, client, status_code=replay.status_code,
                        latency_ms=_ms(started), replayed=True,
                    )
                    return replay.payload
    except Exception as exc:  # noqa: BLE001 — recorded, then re-raised unchanged
        _audit_failure(request, payload, client, exc, _ms(started))
        raise

    gate = await container.integration_concurrency.acquire(
        client.key_id,
        limit=client.max_concurrency,
        queue_depth=settings.integration_queue_depth,
    )
    released = False

    try:
        chat_request = ChatRequest(
            question=payload.query,
            top_k=payload.retrieval.top_k,
            category=payload.retrieval.category,
            document_ids=payload.retrieval.document_ids or None,
        )

        def _answer() -> ChatResponse:
            # The gate is set inside the worker rather than around the await, so the
            # veto is established in the thread that will actually reach the search
            # rather than relying on how context is carried across the boundary.
            with web_search_gate(web_allowed):
                return container.rag_service.answer(chat_request, user=client.user, channel="erp")

        task = asyncio.ensure_future(run_in_threadpool(_answer))
        try:
            chat_response = await asyncio.wait_for(
                asyncio.shield(task), timeout=settings.integration_answer_budget_seconds
            )
        except (TimeoutError, asyncio.TimeoutError) as exc:
            # The generation cannot be cancelled once it is with the model, so the slot
            # stays held until it finishes. Releasing it now would let a second call
            # start against a model that is still busy with the first, which is how a
            # timeout turns into a queue.
            task.add_done_callback(lambda _: container.integration_concurrency.release(gate))
            released = True
            raise RagTimeoutError(
                "لم تكتمل الإجابة داخل المهلة المسموحة.",
                headers={"Retry-After": "5"},
            ) from exc

        result = _to_response(payload, chat_response)
        latency = _ms(started)
        result.latency_ms.total = latency

        serialised = result.model_dump(mode="json")
        with session_scope() as db:
            if idempotency_key:
                container.integration_idempotency.complete(
                    db,
                    client_id=client.client_id,
                    key=idempotency_key,
                    status_code=200,
                    payload=serialised,
                    answer_id=result.answer_id,
                )
        _audit(payload, client, status_code=200, latency_ms=latency, result=result)
        return serialised

    except Exception as exc:  # noqa: BLE001
        # A claim that produced no answer has to be let go, or every retry is told a
        # request is still running until the row expires hours from now.
        if idempotency_key:
            with session_scope() as db:
                container.integration_idempotency.abandon(
                    db, client_id=client.client_id, key=idempotency_key
                )
        _audit_failure(request, payload, client, exc, _ms(started))
        raise
    finally:
        if not released:
            container.integration_concurrency.release(gate)


