def _ms(since: float) -> int:
    return int((time.perf_counter() - since) * 1000)


def _audit(
    payload: ErpQueryRequest | None,
    client: AuthenticatedClient | None,
    *,
    status_code: int,
    latency_ms: int,
    error_code: str = "",
    result: ErpQueryResponse | None = None,
    replayed: bool = False,
    request_id: str = "",
) -> None:
    """One row per call, holding identifiers and counts and no content.

    No question text, no answer text, no ERP values. The answer trace already keeps the
    question under its own retention rules; copying it here would put the same sensitive
    text in a second place with a second lifetime and a second person who has to
    remember to delete it. What this row is for is the join — an ERP log line carries
    `request_id`, and from here it reaches `answer_id`, and from there the evidence.

    Never allowed to fail the call: losing the audit row must not lose the answer
    somebody is waiting for.
    """
    try:
        with session_scope() as db:
            db.add(
                IntegrationRequest(
                    id=str(uuid.uuid4()),
                    # Falls back to the id read off the raw body before it was trusted.
                    # A request refused by the parser has no parsed payload, and that is
                    # exactly the call whose correlation id somebody will come looking
                    # for — a call log that drops the id on failures traces only the
                    # requests that never needed tracing.
                    request_id=((payload.request_id if payload else "") or request_id)[:64],
                    client_id=client.client_id if client else "",
                    tenant_id=client.tenant_id if client else "",
                    external_user_id=(
                        payload.end_user.external_user_id[:64] if payload else ""
                    ),
                    endpoint=ENDPOINT_PATH,
                    status_code=status_code,
                    error_code=error_code,
                    answer_id=result.answer_id if result else "",
                    answered=bool(result.answered) if result else False,
                    answer_source=(result.answer_source if result else "") or (
                        "replay" if replayed else ""
                    ),
                    source_counts={
                        "sources": len(result.sources) if result else 0,
                        "knowledge": len(result.knowledge_sources) if result else 0,
                        "web": len(result.web_sources) if result else 0,
                        "erp_facts": len(payload.context.erp_facts) if payload else 0,
                    },
                    query_chars=len(payload.query) if payload else 0,
                    erp_fact_count=len(payload.context.erp_facts) if payload else 0,
                    latency_ms=latency_ms,
                )
            )
    except Exception:  # noqa: BLE001
        logger.exception("Could not record the integration audit row")


def _audit_failure(
    request: Request,
    payload: ErpQueryRequest | None,
    client: AuthenticatedClient | None,
    exc: Exception,
    latency_ms: int,
) -> None:
    status = int(getattr(exc, "status_code", 500) or 500)
    code = getattr(exc, "code", "") or type(exc).__name__
    echoed = getattr(request.state, "request_id", "") or ""
    logger.info(
        "Integration call failed: request_id=%s key=%s status=%s code=%s",
        echoed,
        client.key_id if client else "-",
        status,
        code,
    )
    _audit(
        payload,
        client,
        status_code=status,
        latency_ms=latency_ms,
        error_code=code[:64],
        request_id=echoed,
    )
