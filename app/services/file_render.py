def render_docx(content, path: Path, rtl: bool, reference: str) -> None:
    from docx import Document as Docx
    from docx.enum.table import WD_TABLE_ALIGNMENT
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Cm, Pt, RGBColor

    navy, gold, muted = RGBColor(*NAVY), RGBColor(*GOLD), RGBColor(*MUTED)
    document = Docx()
    section = document.sections[0]
    section.top_margin, section.bottom_margin = Cm(2.2), Cm(2)
    section.left_margin = section.right_margin = Cm(2)
    font_name = "Segoe UI" if (FONT_DIR / "segoeui.ttf").exists() else "Tahoma"

    normal = document.styles["Normal"]
    normal.font.name = font_name
    normal.font.size = Pt(10.5)
    normal.element.rPr.rFonts.set(qn("w:cs"), font_name)
    normal.paragraph_format.space_after = Pt(4)

    def right_to_left(paragraph) -> None:
        if not rtl:
            return
        paragraph._p.get_or_add_pPr().append(OxmlElement("w:bidi"))
        paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        for run in paragraph.runs:
            run._r.get_or_add_rPr().append(OxmlElement("w:rtl"))

    def shade(cell, rgb) -> None:
        shading = OxmlElement("w:shd")
        shading.set(qn("w:val"), "clear")
        shading.set(qn("w:fill"), _hex(rgb))
        cell._tc.get_or_add_tcPr().append(shading)

    def bottom_border(paragraph, rgb, size=12) -> None:
        borders = OxmlElement("w:pBdr")
        bottom = OxmlElement("w:bottom")
        for key, value in (("w:val", "single"), ("w:sz", str(size)), ("w:space", "4"), ("w:color", _hex(rgb))):
            bottom.set(qn(key), value)
        borders.append(bottom)
        paragraph._p.get_or_add_pPr().append(borders)

    def page_field(paragraph) -> None:
        for kind, text in (("begin", None), (None, "PAGE"), ("end", None)):
            run = paragraph.add_run()
            if kind:
                field = OxmlElement("w:fldChar")
                field.set(qn("w:fldCharType"), kind)
                run._r.append(field)
            else:
                instruction = OxmlElement("w:instrText")
                instruction.set(qn("xml:space"), "preserve")
                instruction.text = text
                run._r.append(instruction)

    # Header and footer, on every page.
    header = section.header.paragraphs[0]
    if LOGO.exists():
        header.add_run().add_picture(str(LOGO), height=Cm(1.1))
        header.add_run("   ")
    name = header.add_run(COMPANY)
    name.bold, name.font.size, name.font.color.rgb = True, Pt(12), navy
    label = header.add_run(f"   |   {SYSTEM_LABEL}")
    label.font.size, label.font.color.rgb = Pt(8.5), muted
    bottom_border(header, GOLD, size=10)
    right_to_left(header)

    footer = section.footer.paragraphs[0]
    note = footer.add_run((DISCLAIMER_AR if rtl else DISCLAIMER_EN) + "   —   ")
    note.font.size, note.font.color.rgb = Pt(7.5), muted
    page_field(footer)
    right_to_left(footer)

    # Title block.
    title = document.add_paragraph()
    run = title.add_run(content.title)
    run.bold, run.font.size, run.font.color.rgb = True, Pt(20), navy
    bottom_border(title, GOLD, size=8)
    right_to_left(title)

    meta = document.add_table(rows=2, cols=4)
    meta.alignment = WD_TABLE_ALIGNMENT.CENTER
    labels = ["التاريخ", "أُعدّ لـ", "المرجع", "المصادر"] if rtl else ["Date", "Prepared for", "Reference", "Sources"]
    values = [f"{datetime.now():%Y-%m-%d %H:%M}", content.author or "—", reference, str(len(content.sources))]
    if rtl:
        meta._tbl.tblPr.append(OxmlElement("w:bidiVisual"))
    for column, (label_text, value) in enumerate(zip(labels, values)):
        for row, (text, is_label) in enumerate(((label_text, True), (value, False))):
            cell = meta.cell(row, column)
            shade(cell, LIGHT)
            paragraph = cell.paragraphs[0]
            paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
            piece = paragraph.add_run(text)
            piece.font.size = Pt(8 if is_label else 9.5)
            piece.bold = not is_label
            piece.font.color.rgb = muted if is_label else RGBColor(*INK)
    document.add_paragraph()

    for block in content.blocks:
        if block.kind == "lead":
            paragraph = document.add_paragraph()
            piece = paragraph.add_run(block.text)
            piece.bold, piece.font.size, piece.font.color.rgb = True, Pt(12), navy
            properties = paragraph._p.get_or_add_pPr()
            shading = OxmlElement("w:shd")
            shading.set(qn("w:val"), "clear")
            shading.set(qn("w:fill"), _hex(LIGHT))
            properties.append(shading)
            paragraph.paragraph_format.space_after = Pt(10)
            right_to_left(paragraph)
            continue
        if block.kind == "heading":
            paragraph = document.add_paragraph()
            piece = paragraph.add_run(block.text)
            piece.bold, piece.font.size, piece.font.color.rgb = True, Pt(14 if block.level <= 2 else 12), navy
            paragraph.paragraph_format.space_before = Pt(10)
            bottom_border(paragraph, RULE, size=6)
            right_to_left(paragraph)
        elif block.kind == "paragraph":
            right_to_left(document.add_paragraph(block.text))
        elif block.kind == "bullet":
            right_to_left(document.add_paragraph(block.text, style="List Bullet"))
        elif block.kind == "table" and block.rows:
            columns = max(len(r) for r in block.rows)
            table = document.add_table(rows=0, cols=columns)
            table.style = "Table Grid"
            table.alignment = WD_TABLE_ALIGNMENT.CENTER
            if rtl:
                table._tbl.tblPr.append(OxmlElement("w:bidiVisual"))
            for index, row in enumerate(block.rows):
                cells = table.add_row().cells
                for column, value in enumerate(row + [""] * (columns - len(row))):
                    cells[column].text = value
                    paragraph = cells[column].paragraphs[0]
                    right_to_left(paragraph)
                    for piece in paragraph.runs:
                        piece.font.size = Pt(9.5)
                        if index == 0:
                            piece.bold = True
                            piece.font.color.rgb = RGBColor(255, 255, 255)
                    if index == 0:
                        shade(cells[column], NAVY)
                    elif index % 2 == 0:
                        shade(cells[column], ZEBRA)
            document.add_paragraph()

    if content.note:
        paragraph = document.add_paragraph()
        piece = paragraph.add_run(content.note)
        piece.font.color.rgb, piece.font.size = RGBColor(122, 82, 0), Pt(9)
        right_to_left(paragraph)
    if content.sources:
        heading = document.add_paragraph()
        piece = heading.add_run("المصادر" if rtl else "Sources")
        piece.bold, piece.font.size, piece.font.color.rgb = True, Pt(12), navy
        bottom_border(heading, RULE, size=6)
        right_to_left(heading)
        for index, source in enumerate(content.sources, 1):
            paragraph = document.add_paragraph()
            piece = paragraph.add_run(f"[{index}]  {source}")
            piece.font.size, piece.font.color.rgb = Pt(8.5), muted
            right_to_left(paragraph)
    document.save(str(path))


