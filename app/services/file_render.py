"""The company's document template, the same for every file the chat makes.

One look across PDF, Word and Excel: a navy header band with the company's name on every
page, a title block with the date, who it was prepared for and a reference, headings and
tables in the house colours, the sources at the end, and a footer with the page number
and a line saying the document was generated and should be checked before it is relied
on. A logo placed at data/branding/logo.png appears in the header of all three.

Only what is known is printed: the company's registered Arabic name, the reader who asked,
the date. Nothing here invents a stamp, a signature or an approval.
"""

from __future__ import annotations

import re
from datetime import datetime
from pathlib import Path

from app.config import BASE_DIR

COMPANY = "شركة ال يافور للنقليات والمقاولات العامة ذ.م.م"
SYSTEM_LABEL = "نظام المعرفة"
DISCLAIMER_AR = "وثيقة مُولَّدة آليًا من نظام المعرفة — تحقّق من المصادر قبل الاعتماد"
DISCLAIMER_EN = "Generated by the knowledge system — check the sources before relying on it"
LOGO = BASE_DIR / "data" / "branding" / "logo.png"

NAVY = (31, 58, 95)
GOLD = (184, 137, 59)
INK = (33, 37, 41)
MUTED = (110, 117, 125)
LIGHT = (244, 246, 249)
ZEBRA = (249, 250, 252)
RULE = (214, 219, 226)

FONT_DIR = Path(r"C:\Windows\Fonts")


def _fonts() -> tuple[Path, Path]:
    for regular, bold in (("segoeui.ttf", "segoeuib.ttf"), ("tahoma.ttf", "tahomabd.ttf"), ("arial.ttf", "arialbd.ttf")):
        if (FONT_DIR / regular).exists():
            return FONT_DIR / regular, FONT_DIR / bold if (FONT_DIR / bold).exists() else FONT_DIR / regular
    raise FileNotFoundError("No font with Arabic letters found in C:\\Windows\\Fonts")


def _hex(rgb: tuple[int, int, int]) -> str:
    return "".join(f"{c:02X}" for c in rgb)


_EMOJI = re.compile("[\U0001F000-\U0001FAFF☀-➿️]")


def _no_emoji(text: str) -> str:
    """The PDF's font has no emoji; left in, they print as nothing or as boxes."""
    return " ".join(_EMOJI.sub("", text).split())


# -- PDF -------------------------------------------------------------------

def render_pdf(content, path: Path, rtl: bool, reference: str) -> None:
    from fpdf import FPDF
    from fpdf.fonts import FontFace

    regular, bold = _fonts()
    align = "R" if rtl else "L"
    far = "L" if rtl else "R"

    class Branded(FPDF):
        def header(self) -> None:
            self.set_fill_color(*NAVY)
            self.rect(0, 0, self.w, 16, style="F")
            self.set_fill_color(*GOLD)
            self.rect(0, 16, self.w, 0.8, style="F")
            if LOGO.exists():
                self.image(str(LOGO), x=(10 if rtl else self.w - 22), y=2.5, h=11)
            self.set_text_color(255, 255, 255)
            self.set_font("brand", "B", 11.5)
            self.set_xy(10, 3.2)
            self.cell(self.w - 20, 6, COMPANY, align=align)
            self.set_font("brand", "", 8)
            self.set_xy(10, 9.2)
            self.cell(self.w - 20, 5, SYSTEM_LABEL, align=align)
            self.set_text_color(*INK)
            self.set_y(24)

        def footer(self) -> None:
            self.set_y(-14)
            self.set_draw_color(*RULE)
            self.line(10, self.get_y(), self.w - 10, self.get_y())
            self.set_font("brand", "", 7.5)
            self.set_text_color(*MUTED)
            self.set_y(-12)
            self.cell(0, 6, DISCLAIMER_AR if rtl else DISCLAIMER_EN, align=align)
            self.set_y(-12)
            self.cell(0, 6, f"{self.page_no()} / {{nb}}", align=far)
            self.set_text_color(*INK)

    pdf = Branded(format="A4")
    pdf.alias_nb_pages()
    pdf.set_margins(14, 24, 14)
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_font("brand", "", str(regular))
    pdf.add_font("brand", "B", str(bold))
    pdf.set_text_shaping(use_shaping_engine=True, direction="rtl" if rtl else "ltr",
                         script="arab" if rtl else None, language="ar" if rtl else None)
    pdf.add_page()
    width = pdf.w - pdf.l_margin - pdf.r_margin

    # Title block.
    pdf.set_font("brand", "B", 18)
    pdf.set_text_color(*NAVY)
    pdf.multi_cell(width, 10, content.title, align=align, new_x="LMARGIN", new_y="NEXT")
    pdf.set_fill_color(*GOLD)
    pdf.rect(pdf.w - pdf.r_margin - 28 if rtl else pdf.l_margin, pdf.get_y() + 1, 28, 0.9, style="F")
    pdf.ln(5)
    meta = [
        ("التاريخ" if rtl else "Date", f"{datetime.now():%Y-%m-%d %H:%M}"),
        ("أُعدّ لـ" if rtl else "Prepared for", content.author or "—"),
        ("المرجع" if rtl else "Reference", reference),
        ("المصادر" if rtl else "Sources", str(len(content.sources))),
    ]
    pdf.set_font("brand", "", 8.5)
    pdf.set_fill_color(*LIGHT)
    pdf.set_draw_color(*LIGHT)
    cells = list(reversed(meta)) if rtl else meta
    column = width / len(cells)
    top = pdf.get_y()
    for index, (label, value) in enumerate(cells):
        x = pdf.l_margin + index * column
        pdf.set_xy(x, top)
        pdf.set_text_color(*MUTED)
        pdf.cell(column, 5.5, label, align="C", fill=True)
        pdf.set_xy(x, top + 5.5)
        pdf.set_text_color(*INK)
        pdf.set_font("brand", "B", 9)
        pdf.cell(column, 6.5, value[:40], align="C", fill=True)
        pdf.set_font("brand", "", 8.5)
    pdf.set_y(top + 16)

    # Body.
    for block in content.blocks:
        if block.kind == "heading":
            pdf.ln(2.5)
            pdf.set_font("brand", "B", 13.5 if block.level <= 2 else 12)
            pdf.set_text_color(*NAVY)
            pdf.multi_cell(width, 8, block.text, align=align, new_x="LMARGIN", new_y="NEXT")
            pdf.set_draw_color(*RULE)
            pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
            pdf.ln(2)
            pdf.set_text_color(*INK)
        elif block.kind == "lead":
            # The direct answer, set apart so it is the first thing read.
            pdf.set_font("brand", "B", 11.5)
            pdf.set_fill_color(*LIGHT)
            pdf.set_text_color(*NAVY)
            pdf.multi_cell(width, 7.5, _no_emoji(block.text), align=align, fill=True, padding=(2.5, 3),
                           new_x="LMARGIN", new_y="NEXT")
            pdf.set_text_color(*INK)
            pdf.ln(2.5)
        elif block.kind == "paragraph":
            pdf.set_font("brand", "", 10.5)
            pdf.multi_cell(width, 6.6, _no_emoji(block.text), align=align, new_x="LMARGIN", new_y="NEXT")
            pdf.ln(1.2)
        elif block.kind == "bullet":
            # The bullet drawn on its own, at the line's start — right for Arabic. Inside
            # the shaped text it landed at the far end of a right-to-left line.
            pdf.set_font("brand", "", 10.5)
            indent = 6
            top = pdf.get_y()
            pdf.set_x(pdf.l_margin + (0 if rtl else indent))
            pdf.multi_cell(width - indent, 6.4, _no_emoji(block.text), align=align, new_x="LMARGIN", new_y="NEXT")
            bottom = pdf.get_y()
            pdf.set_xy(pdf.w - pdf.r_margin - indent if rtl else pdf.l_margin, top)
            pdf.set_text_color(*GOLD)
            pdf.cell(indent, 6.4, "•", align="C")
            pdf.set_text_color(*INK)
            pdf.set_y(bottom + 0.6)
        elif block.kind == "table" and block.rows:
            pdf.ln(1.5)
            pdf.set_font("brand", "", 9)
            columns = max(len(r) for r in block.rows)
            rows = [r + [""] * (columns - len(r)) for r in block.rows]
            rows = [list(reversed(r)) for r in rows] if rtl else rows
            pdf.set_draw_color(*RULE)
            with pdf.table(
                text_align="RIGHT" if rtl else "LEFT", line_height=6.2, borders_layout="HORIZONTAL_LINES",
                headings_style=FontFace(emphasis="BOLD", color=(255, 255, 255), fill_color=NAVY),
                cell_fill_color=ZEBRA, cell_fill_mode="ROWS",
            ) as table:
                for row in rows:
                    cells_row = table.row()
                    for value in row:
                        cells_row.cell(value)
            pdf.ln(3)

    if content.note:
        pdf.ln(2)
        pdf.set_font("brand", "", 9)
        pdf.set_fill_color(253, 241, 220)
        pdf.set_text_color(122, 82, 0)
        pdf.multi_cell(width, 6, content.note, align=align, fill=True, new_x="LMARGIN", new_y="NEXT")
        pdf.set_text_color(*INK)

    if content.sources:
        pdf.ln(4)
        pdf.set_font("brand", "B", 11)
        pdf.set_text_color(*NAVY)
        pdf.multi_cell(width, 7, "المصادر" if rtl else "Sources", align=align, new_x="LMARGIN", new_y="NEXT")
        pdf.set_draw_color(*RULE)
        pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
        pdf.ln(1.5)
        pdf.set_font("brand", "", 8.5)
        pdf.set_text_color(*MUTED)
        for index, source in enumerate(content.sources, 1):
            pdf.multi_cell(width, 5.4, f"[{index}]  {source}", align=align, new_x="LMARGIN", new_y="NEXT")
        pdf.set_text_color(*INK)
    pdf.output(str(path))


