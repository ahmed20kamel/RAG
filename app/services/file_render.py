def style_sheet(sheet, title: str, author: str, reference: str, rtl: bool, width: int) -> int:
    """The branded top of a sheet; returns the row the table starts on."""
    from openpyxl.drawing.image import Image as SheetImage
    from openpyxl.styles import Alignment, Font, PatternFill

    sheet.sheet_view.rightToLeft = rtl
    sheet.sheet_view.showGridLines = False
    last = max(width, 4)
    for row, (text, size, fill, color) in enumerate((
        (COMPANY, 14, _hex(NAVY), "FFFFFF"),
        (title, 13, None, _hex(NAVY)),
        (f"{datetime.now():%Y-%m-%d %H:%M}   ·   {author or '—'}   ·   {reference}", 9, None, _hex(MUTED)),
    ), 1):
        sheet.merge_cells(start_row=row, start_column=1, end_row=row, end_column=last)
        cell = sheet.cell(row=row, column=1, value=text)
        cell.font = Font(bold=row < 3, size=size, color=color)
        cell.alignment = Alignment(horizontal="right" if rtl else "left", vertical="center")
        if fill:
            for column in range(1, last + 1):
                sheet.cell(row=row, column=column).fill = PatternFill("solid", fgColor=fill)
    sheet.row_dimensions[1].height = 30
    sheet.row_dimensions[2].height = 24
    if LOGO.exists():
        logo = SheetImage(str(LOGO))
        logo.height, logo.width = 36, int(36 * logo.width / max(logo.height, 1))
        sheet.add_image(logo, "A1")
    # Printed: landscape, one page wide, the company and page number on every page.
    sheet.page_setup.orientation = "landscape"
    sheet.page_setup.fitToWidth = 1
    sheet.page_setup.fitToHeight = 0
    sheet.sheet_properties.pageSetUpPr.fitToPage = True
    sheet.oddHeader.right.text = COMPANY
    sheet.oddFooter.left.text = "&P / &N"
    sheet.oddFooter.right.text = DISCLAIMER_AR if rtl else DISCLAIMER_EN
    return 5
